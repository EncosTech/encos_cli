"""Validate the prebuilt CI toolchain. Never download or install dependencies."""
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil

ROOT = Path(__file__).resolve().parents[2]
NODE = '24.22.1'
DRIVER = json.loads((ROOT / 'packages/emcli-native/manifest.json').read_text())['builtAgainstDriver']
REVISION = '20261123-v2'


def validate_toolchain(root, system, arch, lock_digest):
    manifest = root / 'toolchain.json'
    if not manifest.is_file():
        raise ValueError(f'Prebuilt CI toolchain missing at {root}; provision the base environment first')
    config = json.loads(manifest.read_text())
    expected = {'schemaVersion': 1, 'platform': system, 'arch': arch, 'node': NODE,
                'driver': DRIVER, 'pnpm': '12.15.0', 'lockSha256': lock_digest}
    if any(config.get(key) != value for key, value in expected.items()):
        raise ValueError('Prebuilt CI toolchain or dependency lock differs; rebuild the base environment')
    windows = system == 'Windows'
    node_root = root / f'node-v{NODE}-{"win" if windows else "linux"}-{arch}'
    node = node_root / ('node.exe' if windows else 'bin/node')
    headers = (root / f'node-v{NODE}' if windows else node_root) / 'include/node'
    sdk = root / 'sdk/usr'
    for path in [node, headers / 'node_api.h', sdk / 'include/encos/adapter/base_adapter.h']:
        key = path.relative_to(root).as_posix()
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != config.get('files', {}).get(key):
            raise ValueError(f'Prebuilt CI toolchain checksum mismatch: {key}')
    for folder in ['corepack', 'pnpm-store', 'cache'] + (['python'] if windows else []):
        if not (root / folder).is_dir():
            raise ValueError(f'Prebuilt CI dependency cache missing: {folder}')
    return {'node': str(node), 'headers': str(headers), 'sdk': str(sdk),
            'corepack': str(root / 'corepack'), 'store': str(root / 'pnpm-store'),
            'cache': str(root / 'cache'), 'python': str(root / 'python'), 'npmrc': str(root / 'npmrc')}


def main():
    system = platform.system()
    arch = {'AMD64': 'x64', 'x86_64': 'x64', 'aarch64': 'arm64'}[platform.machine()]
    root = Path(os.environ.get('EMCLI_CI_TOOLCHAIN_ROOT', f'/opt/emcli-ci/{REVISION}')).resolve()
    config = validate_toolchain(root, system, arch, hashlib.sha256((ROOT / 'pnpm-lock.yaml').read_bytes()).hexdigest())
    work = ROOT / 'build/ci'
    work.mkdir(parents=True, exist_ok=True)
    if system == 'Windows':
        # Import libraries are generated by the build; keep the shared SDK read-only.
        shutil.copytree(config['sdk'], work / 'sdk/usr', dirs_exist_ok=True)
        config['sdk'] = str(work / 'sdk/usr')
    (work / 'environment.json').write_text(json.dumps(config))
    print(f'Using prebuilt CI toolchain: Node {NODE}, driver {DRIVER}, pnpm 12.15.0 ({root})')


if __name__ == '__main__':
    main()
